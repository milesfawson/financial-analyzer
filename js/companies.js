// Function to search companies by name or ticker
function searchCompanies(query, excludeSelected = []) {
    if (!query || query.length < 1) {
        return [];
    }

    const lowerQuery = query.toLowerCase();

    return FORTUNE_500
        .filter(company => {
            // Exclude already selected companies
            if (excludeSelected.some(s => s.cik === company.cik)) {
                return false;
            }

            // Filter out companies without valid CIK
            if (!company.cik || company.cik === "N/A") {
                return false;
            }

            // Match by name or ticker
            return company.name.toLowerCase().includes(lowerQuery) ||
                   company.ticker.toLowerCase().includes(lowerQuery);
        })
        .slice(0, 10); // Limit results to 10
}

// Function to get a company by CIK
function getCompanyByCik(cik) {
    return FORTUNE_500.find(company => company.cik === cik);
}

